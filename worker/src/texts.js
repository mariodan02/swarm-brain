/** The text for `key` in `lang` (Italian when the language is unknown), with {name} values filled in. */
export function t(lang, key, values = {}) {
  const text = (TEXTS[lang] ?? TEXTS.it)[key];
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in values ? String(values[name]) : m));
}
